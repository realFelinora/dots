local mainMod = "SUPER"

-- Programlar
hl.bind(mainMod .. " + Return",         hl.dsp.exec_cmd(terminal))
hl.bind(mainMod .. " + B",              hl.dsp.exec_cmd(browser))
hl.bind(mainMod .. " + D",              hl.dsp.exec_cmd(discord))
hl.bind(mainMod .. " + P",              hl.dsp.exec_cmd(spotify))
hl.bind(mainMod .. " + SHIFT + E",      hl.dsp.exec_cmd(fileManager))
hl.bind("Print",                        hl.dsp.exec_cmd(screenshot))

-- Felinora shell
hl.bind(mainMod .. " + E", hl.dsp.exec_cmd(shell('felinora files ""')))   -- dosya yöneticisi
hl.bind(mainMod .. " + M", hl.dsp.exec_cmd(shell("felinora launcher")))    -- program başlatıcı
hl.bind(mainMod .. " + L", hl.dsp.exec_cmd(shell("felinora session")))     -- çıkış menüsü
hl.bind(mainMod .. " + W", hl.dsp.exec_cmd(shell("wallpaper toggle")))     -- duvar kağıdı seçici

-- Pencereler
hl.bind(mainMod .. " + X", hl.dsp.window.close())
hl.bind(mainMod .. " + V", hl.dsp.window.float({ action = "toggle" }))
hl.bind(mainMod .. " + J", hl.dsp.layout("togglesplit"))   -- sadece dwindle

-- Çalışma alanları: SUPER + [0-9] geç, SUPER + SHIFT + [0-9] pencereyi taşı
for i = 1, 10 do
    local key = i % 10   -- 10 → 0 tuşu
    hl.bind(mainMod .. " + " .. key,         hl.dsp.focus({ workspace = i }))
    hl.bind(mainMod .. " + SHIFT + " .. key, hl.dsp.window.move({ workspace = i }))
end

-- Gizli çalışma alanı
hl.bind(mainMod .. " + S",         hl.dsp.workspace.toggle_special("magic"))
hl.bind(mainMod .. " + SHIFT + S", hl.dsp.window.move({ workspace = "special:magic" }))
hl.bind(mainMod .. " + SHIFT + D", hl.dsp.window.move({ workspace = "+0" }))

-- SUPER + sol/sağ tık sürükle: pencereyi taşı / boyutlandır
hl.bind(mainMod .. " + mouse:272", hl.dsp.window.drag(),   { mouse = true })
hl.bind(mainMod .. " + mouse:273", hl.dsp.window.resize(), { mouse = true })

-- Ses ve parlaklık tuşları
hl.bind("XF86AudioRaiseVolume",  hl.dsp.exec_cmd("wpctl set-volume -l 1 @DEFAULT_AUDIO_SINK@ 5%+"),  { locked = true, repeating = true })
hl.bind("XF86AudioLowerVolume",  hl.dsp.exec_cmd("wpctl set-volume @DEFAULT_AUDIO_SINK@ 5%-"),       { locked = true, repeating = true })
hl.bind("XF86AudioMute",         hl.dsp.exec_cmd("wpctl set-mute @DEFAULT_AUDIO_SINK@ toggle"),      { locked = true })
hl.bind("XF86AudioMicMute",      hl.dsp.exec_cmd("wpctl set-mute @DEFAULT_AUDIO_SOURCE@ toggle"),    { locked = true })
hl.bind("XF86MonBrightnessUp",   hl.dsp.exec_cmd("brightnessctl -e4 -n2 set 5%+"),                   { locked = true, repeating = true })
hl.bind("XF86MonBrightnessDown", hl.dsp.exec_cmd("brightnessctl -e4 -n2 set 5%-"),                   { locked = true, repeating = true })

-- Medya tuşları (playerctl gerekir)
hl.bind("XF86AudioNext", hl.dsp.exec_cmd("playerctl next"),     { locked = true })
hl.bind("XF86AudioPrev", hl.dsp.exec_cmd("playerctl previous"), { locked = true })
hl.bind("XF86AudioPlay", hl.dsp.exec_cmd("playerctl play-pause"), { locked = true })
hl.bind("XF86AudioStop", hl.dsp.exec_cmd("playerctl pause"),    { locked = true })


